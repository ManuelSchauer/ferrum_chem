#!/usr/bin/env python3
"""Generate `crates/ferrum_core/src/desc/mordred_data.rs` from Mordred's atomic property tables.

The values are taken from `mordred._atomic_property` itself (not re-parsed), so
missing entries ("-" in the data files, or beyond the end of a table) become NaN
exactly as in Mordred, and derived properties (vdW volume = 4/3 * pi * r**3) are
the doubles Mordred computes. Index = atomic number; index 0 (dummy atom) is NaN.

Uses the installed mordred-community (`pip install mordredcommunity`):

    python scripts/gen_mordred_data.py
"""
import math
from pathlib import Path

import importlib.metadata

from mordred import _atomic_property as ap

MORDRED_VERSION = importlib.metadata.version("mordredcommunity")

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "crates/ferrum_core/src/desc/mordred_data.rs"
N = 119


def table(name, doc, getter):
    vals = []
    for z in range(N):
        v = float(getter[z])
        vals.append("f64::NAN" if math.isnan(v) else repr(v) if "." in repr(v) or "e" in repr(v) else repr(v) + ".0")
    rows = ",\n".join("    " + ", ".join(vals[i:i + 6]) for i in range(0, N, 6))
    return f"/// {doc}\npub(crate) const {name}: [f64; {N}] = [\n{rows},\n];\n"


out = [
    f"//! mordred-community {MORDRED_VERSION} atomic property tables (`mordred/_atomic_property.py`).\n",
    "//!\n",
    "//! Generated by `scripts/gen_mordred_data.py`; do not edit by hand.\n",
    "//! Index = atomic number; NaN where Mordred has no value (Mordred then reports\n",
    "//! the descriptor as missing).\n\n",
    table("MORDRED_PAULING_EN", "Mordred `pe`: Pauling electronegativity (`pauling_electron_negativity.txt`).",
          ap.pauling),
    "\n",
    table("MORDRED_VDW_VOLUME", "Mordred `v`: van der Waals volume, 4/3·π·r³ (`van_der_waals_radii.txt`).",
          ap.vdw_volume),
]
OUT.write_text("".join(out))
print(f"wrote {OUT}")
