#!/usr/bin/env python3
"""Generate the Mordred reference used by `crates/ferrum_core/tests/mordred_parity.rs`.

Runs mordred-community (the maintained Mordred fork,
https://github.com/JacksonBurns/mordred-community, PyPI `mordredcommunity`)
with **all 2D descriptors** (1613 columns) on `tests/data/parity_molecules.smi`
and writes `tests/data/mordred_parity_reference.csv`. Columns keep Mordred's own
names; the parity test maps them onto FerrumChem columns through
`ferrum_core::desc::mordred_names` (renamed equivalents and `Mordred_`-prefixed
variants). Columns FerrumChem does not implement yet are reported, not failed,
so the same reference serves as the Mordred coverage checklist.

Each molecule is parsed with `Chem.MolFromSmiles` and handed to the Mordred
calculator as is (Mordred applies its own `AddHs` / `RemoveHs` preprocessing).
Values Mordred reports as missing (e.g. BCUT of a disconnected molecule) are
written as `nan`; booleans as `1.0` / `0.0`; a molecule RDKit rejects gets an
`ERR` row.

    pip install mordredcommunity        # or: pip install -e <mordred-community checkout>
    python scripts/generate_mordred_reference.py [smiles_file] [out_csv] [--nproc N]
"""
import argparse
import csv
import importlib.metadata
import math
from collections import Counter
from pathlib import Path

import rdkit
from rdkit import Chem, RDLogger

from mordred import Calculator, descriptors
from mordred.error import MissingValueBase

RDLogger.DisableLog("rdApp.*")

MORDRED_VERSION = importlib.metadata.version("mordredcommunity")
assert MORDRED_VERSION.startswith("2."), MORDRED_VERSION

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "crates/ferrum_core/tests/data"

CALC = Calculator(descriptors, ignore_3D=True)
COLS = [str(d) for d in CALC.descriptors]


def fmt(v):
    """Returns (cell, missing reason or None)."""
    if isinstance(v, MissingValueBase):
        return "nan", str(v.error)
    v = float(v)
    if math.isnan(v):
        return "nan", None
    if math.isinf(v):
        return ("inf" if v > 0 else "-inf"), None
    # 12 significant digits: far below the test tolerance (1e-9 relative)
    # and keeps the 1613-column file small.
    return "%.12g" % v, None


def row(smi):
    m = Chem.MolFromSmiles(smi)
    if m is None:
        return smi, None
    return smi, [fmt(v) for v in CALC(m).values()]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("smiles", nargs="?", default=DATA / "parity_molecules.smi", type=Path)
    ap.add_argument("out", nargs="?", default=DATA / "mordred_parity_reference.csv", type=Path)
    ap.add_argument("--nproc", type=int, default=8)
    args = ap.parse_args()

    smiles = [l.split()[0] for l in args.smiles.read_text().splitlines() if l.strip()]
    missing = Counter()
    from multiprocessing import Pool

    with Pool(args.nproc) as pool, open(args.out, "w", newline="") as out:
        out.write(f"# mordred-community {MORDRED_VERSION} reference, all 2D descriptors "
                  f"(RDKit {rdkit.__version__}), generated by scripts/generate_mordred_reference.py\n")
        w = csv.writer(out, lineterminator="\n")
        w.writerow(["smiles"] + COLS)
        for smi, cells in pool.imap(row, smiles, chunksize=4):
            if cells is None:
                w.writerow([smi, "ERR"] + [""] * (len(COLS) - 1))
                continue
            w.writerow([smi] + [c for c, _ in cells])
            for col, (_, reason) in zip(COLS, cells):
                if reason is not None:
                    missing[col] += 1

    print(f"wrote {args.out} ({len(smiles)} molecules, {len(COLS)} columns)")
    print(f"{len(missing)} columns have missing values; most frequent:")
    for col, k in missing.most_common(15):
        print(f"  {col}: {k}")


if __name__ == "__main__":
    main()
