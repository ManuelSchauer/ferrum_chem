#!/usr/bin/env python3
"""Generate the Mordred reference used by `crates/ferrum_core/tests/mordred_parity.rs`.

Runs the original Mordred 1.2.0 (Moriwaki et al., https://github.com/mordred-descriptor/mordred)
on `tests/data/parity_molecules.smi` and writes `tests/data/mordred_parity_reference.csv`.
Only the Mordred descriptors FerrumChem implements are computed:

- TopologicalIndex: `Radius`, `Diameter`
- ZagrebIndex: `Zagreb2`
- Autocorrelation: `ATS0pe..ATS8pe`, `ATS0v..ATS8v`
- BCUT: `BCUTpe-1h`, `BCUTpe-1l`, `BCUTv-1h`, `BCUTv-1l`

Each molecule is parsed with `Chem.MolFromSmiles` and handed to the Mordred
calculator as is (Mordred applies its own `AddHs` / `RemoveHs` preprocessing).
Values Mordred reports as missing (e.g. BCUT of a disconnected molecule, or an
element without a Pauling electronegativity) are written as `nan`; a molecule
RDKit rejects gets an `ERR` row.

Mordred is not on the CI image and is no longer maintained: point MORDRED_SRC
at a Mordred 1.2.0 checkout (the directory containing the `mordred` package,
default `~/mordred`). Mordred 1.2.0 predates NumPy 2, so the removed NumPy
aliases are shimmed before it is imported:

    MORDRED_SRC=~/mordred python scripts/generate_mordred_reference.py
"""
import csv
import math
import os
import sys
from collections import Counter
from pathlib import Path

import numpy as np

# NumPy >= 1.24 / 2.x removed these aliases; Mordred 1.2.0 still uses them.
for _alias, _target in [
    ("product", np.prod),
    ("float", float),
    ("int", int),
    ("bool", bool),
    ("object", object),
]:
    if not hasattr(np, _alias):
        setattr(np, _alias, _target)

sys.path.insert(0, os.path.expanduser(os.environ.get("MORDRED_SRC", "~/mordred")))

import rdkit  # noqa: E402
from rdkit import Chem, RDLogger  # noqa: E402

import mordred  # noqa: E402
from mordred import Autocorrelation, BCUT, Calculator, TopologicalIndex, ZagrebIndex  # noqa: E402
from mordred.error import MissingValueBase  # noqa: E402

RDLogger.DisableLog("rdApp.*")

assert mordred.__version__ == "1.2.0", mordred.__version__

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "crates/ferrum_core/tests/data"
SMILES_FILE = Path(sys.argv[1]) if len(sys.argv) > 1 else DATA / "parity_molecules.smi"
OUT_FILE = Path(sys.argv[2]) if len(sys.argv) > 2 else DATA / "mordred_parity_reference.csv"

descriptors = [TopologicalIndex.Radius(), TopologicalIndex.Diameter(), ZagrebIndex.ZagrebIndex(2, 1)]
descriptors += [Autocorrelation.ATS(k, prop) for prop in ("pe", "v") for k in range(9)]
descriptors += [BCUT.BCUT(prop, nth) for prop in ("pe", "v") for nth in (0, -1)]
calc = Calculator(descriptors)
cols = [str(d) for d in calc.descriptors]


def fmt(v, counter, col):
    if isinstance(v, MissingValueBase):
        counter[(col, str(v.error))] += 1
        return "nan"
    v = float(v)
    if math.isnan(v):
        return "nan"
    return repr(v)


missing = Counter()
with open(SMILES_FILE) as src, open(OUT_FILE, "w", newline="") as out:
    out.write(f"# Mordred {mordred.__version__} reference (RDKit {rdkit.__version__}), "
              "generated by scripts/generate_mordred_reference.py\n")
    w = csv.writer(out, lineterminator="\n")
    w.writerow(["smiles"] + cols)
    n = 0
    for line in src:
        smi = line.split()[0] if line.strip() else ""
        if not smi:
            continue
        n += 1
        m = Chem.MolFromSmiles(smi)
        if m is None:
            w.writerow([smi, "ERR"] + [""] * (len(cols) - 1))
            continue
        values = list(calc(m).values())
        w.writerow([smi] + [fmt(v, missing, c) for v, c in zip(values, cols)])

print(f"wrote {OUT_FILE} ({n} molecules)")
for (col, err), k in sorted(missing.items()):
    print(f"  {col}: {k} x missing ({err})")
