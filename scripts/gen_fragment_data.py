#!/usr/bin/env python3
"""Generate `crates/ferrum_core/src/desc/rdkit_fragments_data.rs` from RDKit.

The `fr_*` descriptors of `rdkit.Chem.Fragments` are SMARTS match counts read
from RDKit's `FragmentDescriptors.csv`. This copies name and SMARTS in file
order (the order of `Fragments.fns`) for the RDKit version used as reference:

    python scripts/gen_fragment_data.py
"""
import os
from pathlib import Path

import rdkit
from rdkit import RDConfig

OUT = Path(__file__).resolve().parents[1] / "crates/ferrum_core/src/desc/rdkit_fragments_data.rs"
SRC = os.path.join(RDConfig.RDDataDir, "FragmentDescriptors.csv")

entries = []
with open(SRC) as f:
    for line in f:
        if not line or line[0] == "#":
            continue
        parts = line.split("\t")
        if len(parts) < 3:
            continue
        name = parts[0].replace("=", "_").replace("-", "_")
        entries.append((name, parts[2].strip()))

lines = [
    "// @generated by scripts/gen_fragment_data.py -- do not edit by hand.",
    f"// Source: RDKit {rdkit.__version__} FragmentDescriptors.csv",
    "//! `fr_*` fragment SMARTS mirrored from RDKit (`rdkit.Chem.Fragments`).",
    "",
    "/// `(descriptor name, SMARTS)` in RDKit's order.",
    f"pub static FRAGMENTS: [(&str, &str); {len(entries)}] = [",
]
for name, sma in entries:
    lines.append(f"    ({name!r}, {sma!r}),".replace("'", '"') if '"' not in sma else f'    ("{name}", r#"{sma}"#),')
lines.append("];")
lines.append("")
OUT.write_text("\n".join(lines))
print(f"wrote {OUT} ({len(entries)} fragments)")
