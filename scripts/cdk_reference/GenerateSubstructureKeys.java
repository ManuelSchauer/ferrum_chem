// Generates crates/ferrum_core/src/desc/cdk_substructure_keys.rs: the SMARTS keys
// of CDK's SubstructureFingerprinter (default: the 307 functional groups of
// Laggner's SMARTS_InteLigand.txt) and KlekotaRothFingerprinter (4,860 keys),
// read through the fingerprinters themselves (getSubstructure), so the table is
// exactly what CDK matches.
//
//     scripts/cdk_reference/generate_substructure_keys.sh
//
// Requires Java >= 11 and a CDK fat jar (default ~/dev_new/cdk/bundle/target/cdk-2.13-SNAPSHOT.jar).

import java.io.BufferedWriter;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;

import org.openscience.cdk.CDK;
import org.openscience.cdk.fingerprint.KlekotaRothFingerprinter;
import org.openscience.cdk.fingerprint.SubstructureFingerprinter;

public final class GenerateSubstructureKeys {

    private static void table(BufferedWriter w, String doc, String name, SubstructureFingerprinter fp)
            throws Exception {
        w.write(doc);
        w.write("pub(crate) static " + name + ": [&str; " + fp.getSize() + "] = [\n");
        for (int i = 0; i < fp.getSize(); i++) {
            String smarts = fp.getSubstructure(i);
            if (smarts.indexOf('"') >= 0)
                throw new IllegalStateException("quote in SMARTS " + smarts);
            w.write("    r\"" + smarts + "\",\n");
        }
        w.write("];\n");
    }

    public static void main(String[] args) throws Exception {
        Path root = Paths.get(args.length > 0 ? args[0] : ".").toAbsolutePath().normalize();
        Path out = root.resolve("crates/ferrum_core/src/desc/cdk_substructure_keys.rs");
        try (BufferedWriter w = Files.newBufferedWriter(out, StandardCharsets.UTF_8)) {
            w.write("//! SMARTS keys of CDK " + CDK.getVersion() + "'s `SubstructureFingerprinter` (default\n");
            w.write("//! functional groups) and `KlekotaRothFingerprinter`, in bit order.\n");
            w.write("//!\n");
            w.write("//! Generated by scripts/cdk_reference/GenerateSubstructureKeys.java - do not edit.\n\n");
            table(w, "/// CDK `StandardSubstructureSets.getFunctionalGroupSMARTS()` (Laggner's\n"
                     + "/// `SMARTS_InteLigand.txt`), the default keys of `SubstructureFingerprinter`.\n",
                  "CDK_SUBSTRUCTURE_SMARTS", new SubstructureFingerprinter());
            w.write("\n");
            table(w, "/// CDK `KlekotaRothFingerprinter` keys (Klekota & Roth, Bioinformatics 2008).\n",
                  "KLEKOTA_ROTH_SMARTS", new KlekotaRothFingerprinter());
        }
        System.err.println("wrote " + root.relativize(out));
    }
}
