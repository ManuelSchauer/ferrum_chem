#!/usr/bin/env python3
"""Generate the Biosynfoni reference used by `crates/ferrum_core/tests/biosynfoni_parity.rs`.

Runs the original Biosynfoni implementation (Nollen et al., version
`full_1103`, default settings: overlap within and between substructures
allowed, i.e. counts = `len(mol.GetSubstructMatches(key))`) on
`tests/data/parity_molecules.smi` and writes
`tests/data/biosynfoni_parity_reference.csv`.

Biosynfoni is not on the CI image; point BIOSYNFONI_SRC at a checkout's `src`
directory (https://github.com/lucinamay/biosynfoni):

    BIOSYNFONI_SRC=~/dev_new/biosynfoni/src python scripts/generate_biosynfoni_reference.py
"""
import csv
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.expanduser(os.environ.get("BIOSYNFONI_SRC", "~/dev_new/biosynfoni/src")))

import rdkit
from rdkit import Chem, RDLogger
from biosynfoni.concerto_fp import Biosynfoni
from biosynfoni.subkeys.default_version import defaultVersion
from biosynfoni.subkeys.versionfonis import fpVersions

RDLogger.DisableLog("rdApp.*")

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "crates/ferrum_core/tests/data"
SMILES_FILE = Path(sys.argv[1]) if len(sys.argv) > 1 else DATA / "parity_molecules.smi"
OUT_FILE = Path(sys.argv[2]) if len(sys.argv) > 2 else DATA / "biosynfoni_parity_reference.csv"

assert defaultVersion == "full_1103", defaultVersion
keys = fpVersions[defaultVersion]
cols = [f"Biosynfoni_{k}" for k in keys]

with open(SMILES_FILE) as src, open(OUT_FILE, "w", newline="") as out:
    out.write(f"# Biosynfoni {defaultVersion} reference (RDKit {rdkit.__version__}), "
              "generated by scripts/generate_biosynfoni_reference.py\n")
    w = csv.writer(out, lineterminator="\n")
    w.writerow(["smiles"] + cols)
    n = 0
    for line in src:
        smi = line.split()[0] if line.strip() else ""
        if not smi:
            continue
        m = Chem.MolFromSmiles(smi)
        if m is None:
            w.writerow([smi, "ERR"] + [""] * (len(cols) - 1))
        else:
            w.writerow([smi] + Biosynfoni(m).fingerprint)
        n += 1
print(f"wrote {OUT_FILE} ({n} molecules)")
