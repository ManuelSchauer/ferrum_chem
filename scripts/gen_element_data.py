#!/usr/bin/env python3
"""Generate `crates/ferrum_core/src/mol/rdkit_data.rs` from RDKit's periodic table.

FerrumChem reproduces RDKit's valence model, aromaticity and masses, so the
element data must be identical to the RDKit version used as reference.
Re-run this script after upgrading the reference RDKit version:

    python scripts/gen_element_data.py
"""
from pathlib import Path

import rdkit
from rdkit import Chem

OUT = Path(__file__).resolve().parents[1] / "crates/ferrum_core/src/mol/rdkit_data.rs"
MAX_Z = 118

pt = Chem.GetPeriodicTable()


def f(x: float) -> str:
    s = repr(float(x))
    return s if ("." in s or "e" in s) else s + ".0"


lines = []
lines.append("// @generated by scripts/gen_element_data.py -- do not edit by hand.")
lines.append(f"// Source: RDKit {rdkit.__version__} periodic table.")
lines.append("//! Element and isotope data mirrored from RDKit's periodic table.")
lines.append("")
lines.append("/// Version of RDKit this table was generated from.")
lines.append(f'pub const RDKIT_VERSION: &str = "{rdkit.__version__}";')
lines.append("")
lines.append("/// Per-element data as used by RDKit's valence model and descriptors.")
lines.append("#[derive(Debug, Clone, Copy)]")
lines.append("pub struct ElementData {")
lines.append("    /// Average atomic weight.")
lines.append("    pub mass: f64,")
lines.append("    /// Number of outer-shell electrons.")
lines.append("    pub n_outer: u8,")
lines.append("    /// Allowed valences (first entry is the default valence). `-1` means \"any\".")
lines.append("    pub valences: &'static [i8],")
lines.append("    /// Most common isotope (mass number).")
lines.append("    pub common_isotope: u16,")
lines.append("    /// Exact mass of the most common isotope.")
lines.append("    pub common_isotope_mass: f64,")
lines.append("    /// Covalent radius.")
lines.append("    pub r_cov: f64,")
lines.append("    /// Bond radius (`Rb0`).")
lines.append("    pub r_b0: f64,")
lines.append("    /// Van der Waals radius.")
lines.append("    pub r_vdw: f64,")
lines.append("}")
lines.append("")
lines.append(f"pub static ELEMENTS: [ElementData; {MAX_Z + 1}] = [")
for z in range(MAX_Z + 1):
    vals = ", ".join(str(v) for v in pt.GetValenceList(z))
    lines.append(
        f"    ElementData {{ mass: {f(pt.GetAtomicWeight(z))}, n_outer: {pt.GetNOuterElecs(z)}, "
        f"valences: &[{vals}], common_isotope: {pt.GetMostCommonIsotope(z)}, "
        f"common_isotope_mass: {f(pt.GetMostCommonIsotopeMass(z))}, r_cov: {f(pt.GetRcovalent(z))}, "
        f"r_b0: {f(pt.GetRb0(z))}, r_vdw: {f(pt.GetRvdw(z))} }}, // {z} {pt.GetElementSymbol(z)}"
    )
lines.append("];")
lines.append("")

isotopes = []
for z in range(1, MAX_Z + 1):
    for a in range(1, 320):
        m = pt.GetMassForIsotope(z, a)
        if m > 0:
            isotopes.append((z, a, m))
lines.append("/// Exact isotope masses as `(atomic_number, mass_number, mass)`, sorted.")
lines.append(f"pub static ISOTOPE_MASSES: [(u8, u16, f64); {len(isotopes)}] = [")
for z, a, m in isotopes:
    lines.append(f"    ({z}, {a}, {f(m)}),")
lines.append("];")
lines.append("")
lines.append("""/// Exact mass of an isotope (RDKit `getMassForIsotope`), if known.
pub fn isotope_mass(atomic_number: u8, mass_number: u16) -> Option<f64> {
    ISOTOPE_MASSES
        .binary_search_by(|&(z, a, _)| (z, a).cmp(&(atomic_number, mass_number)))
        .ok()
        .map(|i| ISOTOPE_MASSES[i].2)
}

/// RDKit `Atom::getMass`: exact isotope mass for isotope-labelled atoms
/// (falling back to the mass number for unknown isotopes), otherwise the
/// average atomic weight.
pub fn atom_mass(atomic_number: u8, isotope: u16) -> f64 {
    if isotope != 0 {
        match isotope_mass(atomic_number, isotope) {
            Some(m) => m,
            None if atomic_number != 0 => isotope as f64,
            None => 0.0,
        }
    } else {
        ELEMENTS[(atomic_number as usize).min(118)].mass
    }
}
""")

OUT.write_text("\n".join(lines))
print(f"wrote {OUT} ({MAX_Z + 1} elements, {len(isotopes)} isotopes)")
